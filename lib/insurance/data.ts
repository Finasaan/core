// ---- Helper: Get all products across all providers ----

export function getAllProducts() {
  return PROVIDERS.flatMap((p) => p.products);
}

export function getProductsByCategory(category: PolicyCategory) {
  return getAllProducts().filter((p) => p.category === category);
}

export function getProviderBySlug(slug: string) {
  return PROVIDERS.find((p) => p.slug === slug);
}

export function getProductBySlug(slug: string) {
  return getAllProducts().find((p) => p.slug === slug);
}

export function getTakafulProviders() {
  return PROVIDERS.filter((p) => p.type === "takaful" || p.type === "both");
}

export function getConventionalProviders() {
  return PROVIDERS.filter((p) => p.type === "conventional" || p.type === "both");
}

