import {
  SALARY_TAX_SLABS_FY2526,
  PENSION_CREDIT_CAP_RATE,
  formatPKR,
  formatPercent,
} from "./config";

// ============================================================
// Types
// ============================================================

export interface SalaryTaxInput {
  annualGrossSalary: number;    // always annual — caller converts monthly × 12
  pensionContribution: number;  // annual voluntary pension contribution (PKR)
  zakatPaid: number;            // annual zakat paid (PKR)
}

export interface SlabApplication {
  label: string;                // e.g. "12L – 22L"
  slabMin: number;
  slabMax: number | null;
  rate: number;
  taxableInThisSlab: number;    // PKR of the user's income that falls in this slab
  taxInThisSlab: number;        // tax rupees generated by this slab portion
  isActive: boolean;            // true for the topmost slab the user's income reaches
}

export interface SalaryTaxResult {
  grossAnnual: number;
  zakatDeduction: number;
  taxableIncome: number;
  slabBreakdown: SlabApplication[];
  grossTax: number;              // tax before pension credit
  pensionEligible: number;       // capped contribution eligible for credit
  pensionRebate: number;         // rupee amount of pension tax credit
  netAnnualTax: number;          // final tax payable after rebate
  monthlyTax: number;            // netAnnualTax / 12
  netAnnualTakeHome: number;     // grossAnnual - netAnnualTax
  netMonthlyTakeHome: number;    // (grossAnnual - netAnnualTax) / 12
  effectiveRate: number;         // netAnnualTax / grossAnnual (decimal, e.g. 0.08 for 8%)
  marginalRate: number;          // rate of the topmost slab hit
  explanation: string;
}

// ============================================================
// calculateSalaryTax
// ============================================================

export function calculateSalaryTax(input: SalaryTaxInput): SalaryTaxResult {
  const grossAnnual    = Math.max(0, Math.round(input.annualGrossSalary));
  const zakatDeduction = Math.max(0, Math.min(Math.round(input.zakatPaid), grossAnnual));
  const pensionInput   = Math.max(0, Math.round(input.pensionContribution));
  const taxableIncome  = Math.max(0, grossAnnual - zakatDeduction);

  // Find the topmost slab whose min <= taxableIncome
  const activeSlab = SALARY_TAX_SLABS_FY2526.reduce((best, slab) => {
    return taxableIncome >= slab.min ? slab : best;
  }, SALARY_TAX_SLABS_FY2526[0]);

  // Gross tax: fixed base + marginal portion
  const grossTax =
    taxableIncome === 0
      ? 0
      : Math.round(
          activeSlab.baseTax +
          (taxableIncome - activeSlab.min) * activeSlab.rate
        );

  // Build per-slab breakdown for table display
  const slabBreakdown: SlabApplication[] = SALARY_TAX_SLABS_FY2526.map((slab) => {
    if (taxableIncome <= slab.min) {
      return {
        label: slab.label,
        slabMin: slab.min,
        slabMax: slab.max,
        rate: slab.rate,
        taxableInThisSlab: 0,
        taxInThisSlab: 0,
        isActive: false,
      };
    }
    const slabCeil = slab.max ?? Infinity;
    const taxableInThisSlab = Math.max(0, Math.min(taxableIncome, slabCeil) - slab.min);
    const taxInThisSlab = Math.round(taxableInThisSlab * slab.rate);
    return {
      label: slab.label,
      slabMin: slab.min,
      slabMax: slab.max,
      rate: slab.rate,
      taxableInThisSlab,
      taxInThisSlab,
      isActive: slab === activeSlab,
    };
  });

  // Pension tax credit (FBR formula: proportional credit)
  // eligible = min(contribution, PENSION_CREDIT_CAP_RATE × taxableIncome)
  // credit   = (eligible / taxableIncome) × grossTax
  const pensionEligible =
    taxableIncome > 0
      ? Math.min(pensionInput, Math.round(taxableIncome * PENSION_CREDIT_CAP_RATE))
      : 0;
  const pensionRebate =
    taxableIncome > 0 && grossTax > 0
      ? Math.min(grossTax, Math.round((pensionEligible / taxableIncome) * grossTax))
      : 0;

  const netAnnualTax       = Math.max(0, grossTax - pensionRebate);
  const monthlyTax         = Math.round(netAnnualTax / 12);
  const netAnnualTakeHome  = Math.max(0, grossAnnual - netAnnualTax);
  const netMonthlyTakeHome = Math.round(netAnnualTakeHome / 12);
  const effectiveRate      = grossAnnual > 0 ? netAnnualTax / grossAnnual : 0;
  const marginalRate       = activeSlab.rate;

  // Human-readable explanation
  const parts: string[] = [`Based on FY 2025-26 FBR salary tax slabs.`];
  if (zakatDeduction > 0) {
    parts.push(
      `Zakat deduction of ${formatPKR(zakatDeduction)} reduces taxable income to ${formatPKR(taxableIncome)}.`
    );
  }
  if (taxableIncome <= 600_000) {
    parts.push(`Taxable income is within the zero-tax slab — no income tax is payable.`);
  } else {
    parts.push(
      `Gross tax is ${formatPKR(grossTax)} at marginal rate ${formatPercent(marginalRate)}.`
    );
  }
  if (pensionRebate > 0) {
    parts.push(
      `Pension contribution of ${formatPKR(pensionInput)} ` +
      `(${formatPKR(pensionEligible)} eligible) reduces tax by ${formatPKR(pensionRebate)}.`
    );
  }
  if (effectiveRate > 0) {
    parts.push(`Effective tax rate on gross salary is ${formatPercent(effectiveRate)}.`);
  }

  return {
    grossAnnual,
    zakatDeduction,
    taxableIncome,
    slabBreakdown,
    grossTax,
    pensionEligible,
    pensionRebate,
    netAnnualTax,
    monthlyTax,
    netAnnualTakeHome,
    netMonthlyTakeHome,
    effectiveRate,
    marginalRate,
    explanation: parts.join(" "),
  };
}

// ============================================================
// projectSalaryTax — year-by-year data for chart
// ============================================================

export interface SalaryProjectionPoint {
  year: number;
  grossSalary: number;
  annualTax: number;
  netTakeHome: number;
  effectiveRatePct: number; // effectiveRate × 100 — ready for Recharts right Y-axis
}

export function projectSalaryTax(
  baseInput: SalaryTaxInput,
  annualGrowthRate: number, // e.g. 0.10 for 10%
  years: number             // 1–20
): SalaryProjectionPoint[] {
  const safeYears = Math.min(Math.max(1, Math.round(years)), 20);
  const safeRate  = Math.max(0, annualGrowthRate);

  // Scale pension and zakat proportionally with salary
  const base = Math.max(1, baseInput.annualGrossSalary);
  const pensionRatio = baseInput.pensionContribution / base;
  const zakatRatio   = baseInput.zakatPaid / base;

  return Array.from({ length: safeYears }, (_, i) => {
    const year         = i + 1;
    const grossSalary  = Math.round(baseInput.annualGrossSalary * Math.pow(1 + safeRate, i));
    const r = calculateSalaryTax({
      annualGrossSalary:   grossSalary,
      pensionContribution: Math.round(grossSalary * pensionRatio),
      zakatPaid:           Math.round(grossSalary * zakatRatio),
    });
    return {
      year,
      grossSalary:      r.grossAnnual,
      annualTax:        r.netAnnualTax,
      netTakeHome:      r.netAnnualTakeHome,
      effectiveRatePct: Math.round(r.effectiveRate * 1000) / 10,
    };
  });
}
